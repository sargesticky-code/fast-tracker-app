import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {runInNewContext} from "node:vm";
const edge=readFileSync(new URL("../supabase/functions/football-data-direct/index.ts",import.meta.url),"utf8");
const start=edge.indexOf("const MAIN_LEAGUES=");
const end=edge.indexOf("function parseCsv(",start);
assert.ok(start>=0&&end>start);
const sources=runInNewContext(edge.slice(start,end)+
 "\n({sourceDefs,seasonCode,HISTORY_BOOTSTRAP_LEAGUES,ALLOWED_BACKFILL_SEASONS})");
const current=sources.sourceDefs("2627",false);
assert.equal(current.length,22,"unchanged daily source workload");
assert.ok(current.every(x=>x.url.includes("/2627/")&&x.kind==="RESULTS"));
const history=sources.sourceDefs("2526",true);
assert.equal(history.length,7,"one-time bounded historical source workload");
assert.deepEqual([...history.map(x=>x.league)].sort(),["D1","E0","F1","I1","N1","P1","SP1"].sort());
assert.equal(new Set(history.map(x=>x.key)).size,7);
assert.ok(history.every(x=>x.url.startsWith("https://www.football-data.co.uk/mmz4281/2526/")));
assert.ok(history.every(x=>!current.some(y=>y.key===x.key)),"do not overwrite current source metadata");
assert.ok(sources.ALLOWED_BACKFILL_SEASONS.has("2526"));
assert.equal(sources.ALLOWED_BACKFILL_SEASONS.has("2425"),false);
assert.ok(edge.includes('requestUrl.searchParams.get("backfill_season")'));
assert.match(edge,/if\(requestedHistory!==null && !ALLOWED_BACKFILL_SEASONS\.has\(requestedHistory\)\)/);
assert.match(edge,/if\(!force && !historical && hbRes\.data/);
assert.match(edge,/if\(!historical\)\{\s*await db\.from\("source_health"\)/);
assert.match(edge,/coreFilesOk===defs\.length/);
assert.match(edge,/const auth=await db\.rpc\("ft_internal_cron_key_matches"/);
assert.match(edge,/if\(auth\.error\|\|auth\.data!==true\)/);
assert.match(edge,/const changed=!old\|\|old\.content_sha256!==got\.hash/);
assert.doesNotMatch(edge,/cron\.schedule/);
assert.equal((edge.match(/function sourceDefs\(/g)||[]).length,1);
console.log("PHASE19_BOUNDED_7_LEAGUE_HISTORY_BACKFILL_CONTRACT_PASSED");
